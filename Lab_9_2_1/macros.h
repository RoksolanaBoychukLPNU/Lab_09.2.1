#ifndef MACROS_H           // запобігання повторного включення
#define MACROS_H

#ifndef Z                  // константа Z має бути визначена до включення файлу
#error "Constant Z is not defined!"
#endif

                           // піднесення до квадрата
#define SQR(x) ((x)*(x))

                           // модуль (абсолютне значення) числа
#define ABS(x) (((x) < 0) ? -(x) : (x))

                           // максимальне з двох чисел
#define MAX(y,z) (((y) > (z)) ? (y) : (z))

                           // мінімальне з двох чисел
#define MIN(y,z) (((y) < (z)) ? (y) : (z))

                           // квадратний корінь (для невід'ємних чисел)
#define ROOT(x) (((x) >= 0) ? sqrt((double)(x)) : -1)

                           // логічний вираз: 1 <= z < 10 (перша гілка)
#define IN_RANGE(z) ((z) >= 1 && (z) < 10)

                           // виведення повідомлення та значення дійсного числа
                           // символ '#' перетворює параметр на рядок
#define PRINTR(w) puts("rezult :"); \
        printf(#w" = %f\n", (float)(w))

#endif                     // MACROS_H
